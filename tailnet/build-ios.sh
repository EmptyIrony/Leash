#!/usr/bin/env bash
# Builds Tailnet.xcframework (iOS device + simulator, iOS 17+) with gomobile, and the ios/Frameworks/Tailnet.xcconfig
# that links it into the Leash target (ios/Config/Leash.xcconfig includes that file when it exists).
# Run on the Mac with Xcode (command line tools selected) and Go on PATH (brew install go; the Go version go.mod asks
# for is fetched automatically by the go command).
# Output: $OUT (default: ../ios/Frameworks/Tailnet.xcframework, git-ignored).
set -euo pipefail
cd "$(dirname "$0")"

OUT="${OUT:-../ios/Frameworks/Tailnet.xcframework}"
IOSVERSION="${IOSVERSION:-17.0}"
TARGETS="${TARGETS:-ios,iossimulator}"

command -v go >/dev/null || { echo "go not found on PATH (brew install go)" >&2; exit 1; }
[ "$(uname -s)" = Darwin ] || { echo "build-ios.sh must run on macOS with Xcode" >&2; exit 1; }
command -v xcrun >/dev/null && xcrun --sdk iphoneos --show-sdk-path >/dev/null 2>&1 \
  && xcrun --sdk iphonesimulator --show-sdk-path >/dev/null 2>&1 \
  || { echo "Xcode with the iOS and iOS Simulator SDKs is required (sudo xcode-select -s /Applications/Xcode.app)" >&2; exit 1; }

# gomobile bind needs cgo for the iOS targets (it sets CGO_ENABLED itself; stay explicit) and the module graph as
# go.mod pins it (-mod=mod lets go add go.sum lines for tools.go's imports).
export CGO_ENABLED=1
export GOFLAGS="-mod=mod"
export GOWORK=off

# gomobile and gobind at the versions pinned in go.mod (tools.go). No `gomobile init`: with this gomobile it only
# installs gobind@latest over the pinned one, and bind needs nothing else for iOS.
GOBIN="$(go env GOPATH)/bin"
go install golang.org/x/mobile/cmd/gomobile golang.org/x/mobile/cmd/gobind
export PATH="$GOBIN:$PATH"

TAGS="$(tr -d '\n' < build-tags.txt)"
mkdir -p "$(dirname "$OUT")"
XCCONFIG="$(dirname "$OUT")/Tailnet.xcconfig"
# a failed build must not leave an xcconfig that links a framework that is gone
rm -rf "$OUT" "$XCCONFIG"
if ! gomobile bind \
  -target "$TARGETS" -iosversion "$IOSVERSION" \
  -tags "$TAGS" -trimpath -ldflags "-s -w" \
  -o "$OUT" .; then
  cat >&2 <<'EOF'

gomobile bind failed. Things to try:
  - "can't find export data" / "buffer full": a damaged Go build cache. Run  go clean -cache  and build again.
  - "unknown tag" / a package that no longer builds: a tailscale upgrade changed a ts_omit_* tag; remove it from build-tags.txt.
  - "xcrun: error ... SDK": select Xcode with  sudo xcode-select -s /Applications/Xcode.app  and open it once (license).
  - Run the same command with -x -v (add them to the gomobile line) and read the first error.
EOF
  exit 1
fi

# Link settings for the Leash target. The xcframework holds static frameworks, so they are linked, not embedded.
# Slice directories are named by gomobile (ios-arm64, ios-arm64_x86_64-simulator); find them instead of guessing.
DEVICE="" SIM=""
for d in "$OUT"/*/; do
  name="$(basename "$d")"
  case "$name" in
    *simulator*) SIM="$name" ;;
    ios-*) DEVICE="$name" ;;
  esac
done
[ -n "$DEVICE" ] && [ -n "$SIM" ] || { echo "unexpected xcframework layout in $OUT:" >&2; ls "$OUT" >&2; exit 1; }
cat > "$XCCONFIG" <<EOF
// Generated by tailnet/build-ios.sh. Do not edit or commit (ios/Frameworks/ is git-ignored).
FRAMEWORK_SEARCH_PATHS[sdk=iphoneos*] = \$(inherited) "\$(SRCROOT)/Frameworks/$(basename "$OUT")/$DEVICE"
FRAMEWORK_SEARCH_PATHS[sdk=iphonesimulator*] = \$(inherited) "\$(SRCROOT)/Frameworks/$(basename "$OUT")/$SIM"
OTHER_LDFLAGS = \$(inherited) -framework Tailnet -framework Security -framework CoreFoundation -lresolv
EOF
echo "built $OUT"
echo "wrote $XCCONFIG"
